//==============================================================================
// AudioComponent.cpp - オーディオコンポーネント実装
//==============================================================================

#include "AudioComponent.h"

//==============================================================================
// コンストラクタ
//==============================================================================
AudioComponent::AudioComponent()
{
}

//==============================================================================
// デストラクタ
//==============================================================================
AudioComponent::~AudioComponent()
{
	m_Audio.Unload();
}

//==============================================================================
// サウンド読み込み
//==============================================================================
bool AudioComponent::Load(const std::string& fileName)
{
	m_FileName = fileName;
	m_Loaded = m_Audio.Load(fileName);
	return m_Loaded;
}

//==============================================================================
// 開始
//==============================================================================
void AudioComponent::Start()
{
	if (playOnStart && m_Loaded)
	{
		Play(loop);
	}
}

//==============================================================================
// 再生
//==============================================================================
void AudioComponent::Play(bool loop)
{
	m_Audio.Play(loop);
}

//==============================================================================
// 停止
//==============================================================================
void AudioComponent::Stop()
{
	m_Audio.Stop();
}

//==============================================================================
// 一時停止
//==============================================================================
void AudioComponent::Pause()
{
	m_Audio.Pause();
}

//==============================================================================
// 再開
//==============================================================================
void AudioComponent::Resume()
{
	m_Audio.Resume();
}

//==============================================================================
// 音量設定
//==============================================================================
void AudioComponent::SetVolume(float volume)
{
	m_Audio.SetVolume(volume);
}

float AudioComponent::GetVolume() const
{
	return m_Audio.GetVolume();
}

//==============================================================================
// ピッチ設定
//==============================================================================
void AudioComponent::SetPitch(float pitch)
{
	m_Audio.SetPitch(pitch);
}

//==============================================================================
// 再生中かどうか
//==============================================================================
bool AudioComponent::IsPlaying() const
{
	return m_Audio.IsPlaying();
}
