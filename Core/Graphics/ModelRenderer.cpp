//==============================================================================
// ModelRenderer.cpp - モデル描画コンポーネント実装
//==============================================================================

#include "ModelRenderer.h"
#include "Renderer.h"
#include "Core/Object/GameObject.h"
#include "Core/Object/Transform.h"

//==============================================================================
// コンストラクタ
//==============================================================================
ModelRenderer::ModelRenderer()
{
}

//==============================================================================
// デストラクタ
//==============================================================================
ModelRenderer::~ModelRenderer()
{
	// Model, Shaderの所有権は持たない（外部で管理）
}

//==============================================================================
// 描画
//==============================================================================
void ModelRenderer::Render()
{
	if (!m_Model || !m_Shader) return;

	// シェーダー設定
	m_Shader->Set();

	// ワールド行列設定
	Transform* transform = GetGameObject()->GetTransform();
	Renderer::SetWorldMatrix(transform->GetWorldMatrix());

	// モデル描画
	m_Model->Draw();
}

//==============================================================================
// モデル設定
//==============================================================================
void ModelRenderer::SetModel(Model* model)
{
	m_Model = model;
}

//==============================================================================
// シェーダー設定
//==============================================================================
void ModelRenderer::SetShader(IShader* shader)
{
	m_Shader = shader;
}
