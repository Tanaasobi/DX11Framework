#pragma once

//==============================================================================
// Font.h - フォントクラス
//==============================================================================

#include "Core/System/main.h"
#include <dwrite.h>
#include <d2d1.h>
#include <wincodec.h>
#include <unordered_map>

//==============================================================================
// テキストキャッシュエントリ
//==============================================================================
struct TextCacheEntry
{
	ID3D11ShaderResourceView* srv = nullptr;
	float width = 0.0f;
	float height = 0.0f;
};

//==============================================================================
// Font クラス
// - DirectWrite テキストフォーマットの管理
// - レンダリング済みテキストのキャッシュ
//==============================================================================
class Font
{
public:
	Font();
	~Font();

	//--------------------------------------------------------------------------
	// 初期化・終了
	//--------------------------------------------------------------------------
	bool Init(const std::wstring& fontName, float fontSize);
	void Uninit();

	//--------------------------------------------------------------------------
	// テキストのレンダリングとキャッシュ取得
	//--------------------------------------------------------------------------
	TextCacheEntry* GetOrRenderText(const std::wstring& text);

	//--------------------------------------------------------------------------
	// テキスト幅の計測
	//--------------------------------------------------------------------------
	float MeasureWidth(const std::wstring& text);

	//--------------------------------------------------------------------------
	// キャッシュクリア
	//--------------------------------------------------------------------------
	void ClearCache();

	//--------------------------------------------------------------------------
	// フォント情報取得
	//--------------------------------------------------------------------------
	float GetFontSize() const { return m_FontSize; }
	float GetLineHeight() const { return m_LineHeight; }

private:
	//--------------------------------------------------------------------------
	// DirectWrite オブジェクト
	//--------------------------------------------------------------------------
	IDWriteTextFormat* m_TextFormat = nullptr;

	//--------------------------------------------------------------------------
	// フォントパラメータ
	//--------------------------------------------------------------------------
	std::wstring m_FontName;
	float m_FontSize = 0.0f;
	float m_LineHeight = 0.0f;

	//--------------------------------------------------------------------------
	// テキストキャッシュ（文字列 → レンダリング済みテクスチャ）
	//--------------------------------------------------------------------------
	std::unordered_map<std::wstring, TextCacheEntry> m_TextCache;

	//--------------------------------------------------------------------------
	// 最大キャッシュ数
	//--------------------------------------------------------------------------
	static constexpr int MAX_CACHE_ENTRIES = 256;

	//--------------------------------------------------------------------------
	// 内部メソッド
	//--------------------------------------------------------------------------
	TextCacheEntry RenderTextToTexture(const std::wstring& text);
};
